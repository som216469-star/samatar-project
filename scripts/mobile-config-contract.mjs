import assert from 'node:assert/strict';
import fs from 'node:fs';

const packageJson = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const capacitor = JSON.parse(fs.readFileSync(new URL('../capacitor.config.json', import.meta.url), 'utf8'));
const vite = fs.readFileSync(new URL('../vite.config.ts', import.meta.url), 'utf8');
const apiClient = fs.readFileSync(new URL('../src/lib/apiClient.ts', import.meta.url), 'utf8');
const server = fs.readFileSync(new URL('../server.ts', import.meta.url), 'utf8');
const env = fs.readFileSync(new URL('../.env.mobile', import.meta.url), 'utf8');
const app = fs.readFileSync(new URL('../src/App.tsx', import.meta.url), 'utf8');
const authView = fs.readFileSync(new URL('../src/features/auth/AuthView.tsx', import.meta.url), 'utf8');
const styles = fs.readFileSync(new URL('../src/index.css', import.meta.url), 'utf8');

assert.equal(capacitor.appId, 'com.dugsipro.app');
assert.equal(capacitor.webDir, 'dist-mobile');
assert.match(packageJson.scripts['build:mobile'], /vite build --mode mobile/);
assert.match(vite, /outDir: isMobileBuild \? 'dist-mobile' : 'dist'/);
assert.match(vite, /base: isMobileBuild \? '\.\/' : '\/'/);
assert.match(env, /^VITE_API_BASE_URL=https:\/\/samatar-project\.onrender\.com\s*$/m);
assert.match(apiClient, /VITE_API_BASE_URL/);
assert.match(apiClient, /X-Dugsi-Client/);
assert.match(server, /capacitor:\/\/localhost/);
assert.match(server, /https:\/\/localhost/);
assert.match(server, /isCapacitorClient\(req\)/);
assert.match(app, /MODE === 'mobile' && publicRoute === 'signup'/, 'native signup must return to login instead of opening a tokenless dashboard');
assert.match(app, /MODE === 'mobile' && !payload\.token/, 'native login must reject success responses without a bearer token');
assert.ok(app.includes("const isMobileBuild = import.meta.env.MODE === 'mobile';"), 'App must distinguish native and browser routes');
assert.ok(app.includes("useState<PublicRouteId>(isMobileBuild ? 'login' : 'landing')"), 'Native app must start at login; browser remains on the public landing page');
assert.ok(app.includes("if (publicRoute === 'landing' && !isMobileBuild)"), 'Marketing landing page must only render in browser builds');
assert.ok(app.includes("isMobileBuild && publicRoute === 'landing'"), 'Native landing route must fall through to authentication');
assert.ok(authView.includes("import.meta.env.MODE !== 'mobile'"), 'Native auth view must hide the marketing homepage button');
const launcherForeground = fs.readFileSync(new URL('../android/app/src/main/res/drawable-v24/ic_launcher_foreground.xml', import.meta.url), 'utf8');
const iconGenerator = fs.readFileSync(new URL('../scripts/generate-png-icons.cjs', import.meta.url), 'utf8');
assert.match(launcherForeground, /android:fillColor="#06182B"/, 'Android home-screen icon must include the inset navy rounded tile');
assert.match(launcherForeground, /strokeColor="#0A2943"/, 'launcher tile must use a subtle navy edge, not a cyan outer frame');
assert.match(iconGenerator, /insideTile/, 'generated app icons must include the inset navy tile');
assert.match(iconGenerator, /not a bright cyan frame/, 'generated app icons must avoid the old cyan frame');
assert.match(styles, /mobile-safe-bottom/);
assert.match(styles, /prefers-reduced-motion/);

console.log('Mobile contract checks passed: isolated bundle, shared Render API, native CORS and token gating.');
